//! Ready-to-paste code for the most common web stacks.
//!
//! Every snippet is generated from a [`Manifest`], so file names, sizes and
//! `srcset` values are always right. Plain HTML works everywhere (Astro,
//! Hugo, Eleventy, Laravel, Django templates…); the others cover stacks that
//! need something specific.

use super::Manifest;
#[cfg(test)]
use crate::Format;

/// All snippets as `(path, contents)`.
pub fn all(m: &Manifest) -> Vec<(String, String)> {
    vec![
        ("snippets/picture.html".into(), picture_html(m)),
        ("snippets/JxlPicture.tsx".into(), react_component(m)),
        ("snippets/wordpress.php".into(), wordpress_plugin(m)),
        ("snippets/nginx.conf".into(), nginx_conf()),
        ("snippets/apache.htaccess".into(), apache_htaccess()),
    ]
}

/// Escapes text for an HTML attribute value.
fn attr(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('"', "&quot;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// A `<picture>` element: JPEG XL first, then the fallbacks, then `<img>`.
pub fn picture_html(m: &Manifest) -> String {
    let mut out = String::from("<picture>\n");
    for &format in &m.formats[..m.formats.len() - 1] {
        out += &format!(
            "  <source type=\"{}\" srcset=\"{}\" sizes=\"{}\">\n",
            format.mime(),
            attr(&m.srcset(format)),
            attr(&m.sizes)
        );
    }
    let last = *m.formats.last().expect("at least one format");
    let fallback = m
        .fallback()
        .map(|f| format!("{}{}", m.base_url, f.path))
        .unwrap_or_default();
    let loading = if m.hero {
        "loading=\"eager\" fetchpriority=\"high\""
    } else {
        "loading=\"lazy\""
    };
    out += &format!(
        "  <img src=\"{}\" srcset=\"{}\" sizes=\"{}\"\n       width=\"{}\" height=\"{}\" alt=\"{}\" {loading} decoding=\"async\">\n</picture>\n",
        attr(&fallback),
        attr(&m.srcset(last)),
        attr(&m.sizes),
        m.width,
        m.height,
        attr(&m.alt),
    );
    out
}

/// A dependency-free React component (works in Next.js App and Pages
/// routers, Remix, Gatsby, Vite…). `next/image` cannot serve JPEG XL yet, so
/// this renders a `<picture>` directly.
pub fn react_component(m: &Manifest) -> String {
    format!(
        r#"// JxlPicture.tsx — generated by Jixel. Serves JPEG XL to browsers that
// support it and {fallbacks} to the others.
//
// Usage (Next.js):
//   1. Copy the exported folder to `public{base}` (keep manifest.json).
//   2. import manifest from "@/public{base}manifest.json";
//      <JxlPicture manifest={{manifest}} alt="…" />
//
// The component is a plain server-safe component: no "use client" needed.

export type JxlManifest = {{
  width: number;
  height: number;
  base_url: string;
  sizes: string;
  alt: string;
  hero: boolean;
  formats: string[];
  files: {{ path: string; format: string; width: number; height: number; bytes: number }}[];
}};

const MIME: Record<string, string> = {{
  jxl: "image/jxl",
  avif: "image/avif",
  webp: "image/webp",
  jpeg: "image/jpeg",
  png: "image/png",
}};

type Props = {{
  manifest: JxlManifest;
  alt?: string;
  /** Overrides manifest.sizes, e.g. "(min-width: 1024px) 50vw, 100vw". */
  sizes?: string;
  /** Above-the-fold image: load eagerly with high priority. */
  priority?: boolean;
  className?: string;
  style?: React.CSSProperties;
}};

export function JxlPicture({{ manifest: m, alt, sizes, priority, className, style }}: Props) {{
  const srcSet = (format: string) =>
    m.files
      .filter((f) => f.format === format)
      .map((f) => `${{m.base_url}}${{f.path}} ${{f.width}}w`)
      .join(", ");
  const last = m.formats[m.formats.length - 1];
  const fallback = m.files
    .filter((f) => f.format === last)
    .reduce((a, b) => (Math.abs(b.width - 1080) < Math.abs(a.width - 1080) ? b : a));
  const eager = priority ?? m.hero;
  return (
    <picture>
      {{m.formats.slice(0, -1).map((format) => (
        <source key={{format}} type={{MIME[format]}} srcSet={{srcSet(format)}} sizes={{sizes ?? m.sizes}} />
      ))}}
      <img
        src={{`${{m.base_url}}${{fallback.path}}`}}
        srcSet={{srcSet(last)}}
        sizes={{sizes ?? m.sizes}}
        width={{m.width}}
        height={{m.height}}
        alt={{alt ?? m.alt}}
        loading={{eager ? "eager" : "lazy"}}
        fetchPriority={{eager ? "high" : "auto"}}
        decoding="async"
        className={{className}}
        style={{{{ height: "auto", maxWidth: "100%", ...style }}}}
      />
    </picture>
  );
}}

export default JxlPicture;
"#,
        fallbacks = m.formats[1..]
            .iter()
            .map(|f| f.label())
            .collect::<Vec<_>>()
            .join(" / "),
        base = m.base_url,
    )
}

/// A WordPress must-use plugin: allows `.jxl` uploads and adds a `[jixel]`
/// shortcode that renders a Jixel export folder as `<picture>`.
pub fn wordpress_plugin(m: &Manifest) -> String {
    format!(
        r#"<?php
/**
 * Plugin Name: Jixel – JPEG XL images
 * Description: Allows .jxl uploads and adds the [jixel] shortcode for responsive JPEG XL images exported by Jixel.
 * Version:     1.0.0
 * License:     Apache-2.0
 *
 * Install: copy this file to wp-content/mu-plugins/jixel.php (create the
 * folder if needed). Must-use plugins are active automatically.
 *
 * Use an export:
 *   1. Upload the exported folder to wp-content/uploads/jixel/{name}/
 *      (with manifest.json), e.g. via SFTP.
 *   2. Insert the shortcode in a post or page:   [jixel name="{name}"]
 *      Options: alt="…" sizes="…" priority="1" class="…"
 *   In PHP templates:  echo jixel_picture('{name}');
 */

if (!defined('ABSPATH')) {{
    exit;
}}

// 1. WordPress refuses unknown file types: register JPEG XL.
add_filter('upload_mimes', function ($mimes) {{
    $mimes['jxl'] = 'image/jxl';
    return $mimes;
}});

// 2. WordPress also double-checks the content; PHP may not know JPEG XL yet.
add_filter('wp_check_filetype_and_ext', function ($data, $file, $filename, $mimes) {{
    if (strtolower(substr($filename, -4)) === '.jxl') {{
        $data['ext'] = 'jxl';
        $data['type'] = 'image/jxl';
        $data['proper_filename'] = $filename;
    }}
    return $data;
}}, 10, 4);

/**
 * Renders a Jixel export as a <picture> element.
 *
 * @param string $name  Folder name under wp-content/uploads/jixel/.
 * @param array  $attrs Optional: alt, sizes, priority, class.
 */
function jixel_picture($name, $attrs = array())
{{
    $name = sanitize_file_name($name);
    $uploads = wp_upload_dir();
    $dir = trailingslashit($uploads['basedir']) . 'jixel/' . $name . '/';
    $url = trailingslashit($uploads['baseurl']) . 'jixel/' . $name . '/';
    $json = @file_get_contents($dir . 'manifest.json');
    $m = $json ? json_decode($json, true) : null;
    if (!$m || empty($m['formats'])) {{
        return '<!-- jixel: manifest not found for "' . esc_html($name) . '" -->';
    }}

    $mime = array('jxl' => 'image/jxl', 'avif' => 'image/avif', 'webp' => 'image/webp', 'jpeg' => 'image/jpeg', 'png' => 'image/png');
    $sizes = isset($attrs['sizes']) ? $attrs['sizes'] : $m['sizes'];
    $alt = isset($attrs['alt']) ? $attrs['alt'] : $m['alt'];
    $eager = !empty($attrs['priority']) || !empty($m['hero']);
    $srcset = function ($format) use ($m, $url) {{
        $parts = array();
        foreach ($m['files'] as $f) {{
            if ($f['format'] === $format) {{
                $parts[] = $url . $f['path'] . ' ' . intval($f['width']) . 'w';
            }}
        }}
        return implode(', ', $parts);
    }};

    $last = end($m['formats']);
    $fallback = null;
    foreach ($m['files'] as $f) {{
        if ($f['format'] === $last && ($fallback === null || abs($f['width'] - 1080) < abs($fallback['width'] - 1080))) {{
            $fallback = $f;
        }}
    }}

    $html = '<picture>';
    foreach (array_slice($m['formats'], 0, -1) as $format) {{
        $html .= sprintf('<source type="%s" srcset="%s" sizes="%s">', esc_attr($mime[$format]), esc_attr($srcset($format)), esc_attr($sizes));
    }}
    $html .= sprintf(
        '<img src="%s" srcset="%s" sizes="%s" width="%d" height="%d" alt="%s" class="%s" loading="%s" fetchpriority="%s" decoding="async">',
        esc_url($url . $fallback['path']),
        esc_attr($srcset($last)),
        esc_attr($sizes),
        intval($m['width']),
        intval($m['height']),
        esc_attr($alt),
        esc_attr(isset($attrs['class']) ? $attrs['class'] : ''),
        $eager ? 'eager' : 'lazy',
        $eager ? 'high' : 'auto'
    );
    return $html . '</picture>';
}}

add_shortcode('jixel', function ($atts) {{
    $atts = shortcode_atts(array('name' => '', 'alt' => null, 'sizes' => null, 'priority' => '', 'class' => ''), $atts, 'jixel');
    return jixel_picture($atts['name'], array_filter($atts, function ($v) {{ return $v !== null && $v !== ''; }}));
}});
"#,
        name = m.name
    )
}

/// nginx: correct MIME type, long caching, and optional content negotiation.
pub fn nginx_conf() -> String {
    r#"# nginx configuration for JPEG XL — generated by Jixel.
#
# A) Required: serve .jxl with the right MIME type and cache it for a year
#    (exported file names never change content). Put inside your `server` block.
location ~* \.jxl$ {
    types { }
    default_type image/jxl;
    add_header Cache-Control "public, max-age=31536000, immutable";
}
location ~* \.(avif|webp|jpe?g|png)$ {
    add_header Cache-Control "public, max-age=31536000, immutable";
}

# B) Optional: content negotiation. Keep using photo.jpg in your HTML/CMS and
#    nginx answers with photo.jxl (same folder, same name) to browsers that
#    accept JPEG XL. Not needed when you use the <picture> snippet.
#
#    This `map` goes in the `http` block (e.g. /etc/nginx/conf.d/jxl.conf):
#
# map $http_accept $jxl_suffix {
#     default        "";
#     "~*image/jxl"  ".jxl";
# }
#
#    and this replaces the second location above, inside `server`:
#
# location ~* ^(?<jxl_base>.+)\.(jpe?g|png)$ {
#     add_header Vary Accept;
#     add_header Cache-Control "public, max-age=31536000, immutable";
#     try_files $jxl_base$jxl_suffix $uri =404;
# }
#
#    If a CDN sits in front of nginx, make sure it honours `Vary: Accept`
#    (or disable negotiation and use <picture>).
"#
    .to_string()
}

/// Apache (`.htaccess`): MIME type, caching, optional content negotiation.
pub fn apache_htaccess() -> String {
    r#"# Apache configuration for JPEG XL — generated by Jixel.
# Put this in the .htaccess of your images folder (or the site root).

# A) Required: the JPEG XL MIME type.
AddType image/jxl .jxl

# Long caching: exported file names never change content.
<IfModule mod_headers.c>
    <FilesMatch "\.(jxl|avif|webp|jpe?g|png)$">
        Header set Cache-Control "public, max-age=31536000, immutable"
    </FilesMatch>
</IfModule>

# B) Optional: content negotiation. Keep photo.jpg in your HTML/CMS; browsers
#    that accept JPEG XL receive photo.jxl from the same folder instead.
#    Not needed when you use the <picture> snippet.
<IfModule mod_rewrite.c>
    RewriteEngine On
    RewriteCond %{HTTP_ACCEPT} image/jxl
    RewriteCond %{REQUEST_FILENAME} ^(.+)\.(jpe?g|png)$
    RewriteCond %1.jxl -f
    RewriteRule ^(.+)\.(jpe?g|png)$ $1.jxl [T=image/jxl,L]
</IfModule>
<IfModule mod_headers.c>
    <FilesMatch "\.(jpe?g|png)$">
        Header append Vary Accept
    </FilesMatch>
</IfModule>
"#
    .to_string()
}

/// Lowercase name used for formats in `manifest.json` (serde names).
#[cfg(test)]
fn manifest_name(format: Format) -> String {
    serde_json::to_value(format)
        .ok()
        .and_then(|v| v.as_str().map(str::to_owned))
        .unwrap_or_default()
}

#[cfg(test)]
mod tests {
    use super::super::{Manifest, WebFile};
    use super::*;

    fn manifest() -> Manifest {
        let file = |format: Format, width| WebFile {
            path: format!("p-{width}.{}", format.extension()),
            format,
            width,
            height: width / 2,
            bytes: 100,
        };
        Manifest {
            name: "p".into(),
            width: 1080,
            height: 540,
            base_url: "/img/".into(),
            sizes: "100vw".into(),
            alt: "A \"quoted\" <alt>".into(),
            hero: false,
            formats: vec![Format::Jxl, Format::Jpeg],
            files: vec![
                file(Format::Jxl, 480),
                file(Format::Jxl, 1080),
                file(Format::Jpeg, 480),
                file(Format::Jpeg, 1080),
            ],
            totals: vec![],
        }
    }

    #[test]
    fn picture_lists_jxl_first_and_escapes_alt() {
        let html = picture_html(&manifest());
        assert!(html.contains(
            "<source type=\"image/jxl\" srcset=\"/img/p-480.jxl 480w, /img/p-1080.jxl 1080w\""
        ));
        assert!(html.contains("src=\"/img/p-1080.jpg\""));
        assert!(html.contains("alt=\"A &quot;quoted&quot; &lt;alt&gt;\""));
        assert!(html.contains("loading=\"lazy\""));
    }

    #[test]
    fn format_names_match_the_react_and_php_mime_tables() {
        for f in [
            Format::Jxl,
            Format::Avif,
            Format::Webp,
            Format::Jpeg,
            Format::Png,
        ] {
            let name = manifest_name(f);
            assert!(
                react_component(&manifest()).contains(&format!("{name}: \"{}\"", f.mime())),
                "{name}"
            );
            assert!(
                wordpress_plugin(&manifest()).contains(&format!("'{name}' => '{}'", f.mime())),
                "{name}"
            );
        }
    }
}
